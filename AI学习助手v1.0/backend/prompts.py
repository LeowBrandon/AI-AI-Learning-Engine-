"""四套系统提示词，与《功能需求文档.md》第四节一一对应。

两个实现上的必要处理：

1. 文档里的提示词把「# 输入」也写在了一起。多轮对话必须拆开：
   角色与规则放 system，资料放 system 末尾，学员的问题作为 user 消息。
   否则每轮都要重建 system，历史对话没处放。

2. 模板里的占位符用 {{name}}，用 str.replace 填充而**不能用 str.format**——
   提示词里有 JSON 示例，含大量裸的 { }，format 会直接抛异常。
"""


def render(template, **values):
    """把 {{key}} 换成对应值。没传的占位符原样保留，便于发现漏填。"""
    text = template
    for key, value in values.items():
        text = text.replace('{{%s}}' % key, str(value))
    return text


